"""The generated tool catalogue (MPC001-143): ``cerp catalogue``.

Built from the running server (registry + exposure + curated tools), never written by hand. For each tool:
name, title, description, required scope, annotations, kill-switch keys and the input and output schemas.
JSON for CI diffs (``tests/golden/catalogue.json``), Markdown for people.
"""

from __future__ import annotations

import json
from typing import Any

import anyio
from mcp import Client
from mcp.server.mcpserver import MCPServer

from cerp.protocol.naming import TOOL_CATALOGUE_VERSION
from cerp.protocol.scopes import scope_for


def build_catalogue(mcp: MCPServer) -> dict[str, Any]:
    async def tools() -> list[Any]:
        async with Client(mcp) as c:
            return list((await c.list_tools()).tools)

    out = []
    for t in sorted(anyio.run(tools), key=lambda t: t.name):
        ann = t.annotations.model_dump(by_alias=True, exclude_none=True) if t.annotations else {}
        read_only = bool(ann.get("readOnlyHint"))
        module = t.name.split(".", 1)[0]
        out.append(
            {
                "name": t.name,
                "title": t.title,
                "description": t.description,
                "scope": scope_for(t.name, read_only=read_only),
                "annotations": ann,
                "kill_switches": [f"tool:{t.name}", f"module:{module}"] + ([] if read_only else ["writes"]),
                "input_schema": t.input_schema,
                "output_schema": t.output_schema,
            }
        )
    return {"catalogue_version": TOOL_CATALOGUE_VERSION, "tools": out}


def to_json(cat: dict[str, Any]) -> str:
    return json.dumps(cat, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def to_markdown(cat: dict[str, Any]) -> str:
    lines = [
        "# Tool catalogue",
        "",
        f"Generated by `cerp catalogue` (catalogue version {cat['catalogue_version']}); do not edit by hand.",
        "",
        "| Tool | Title | Scope | Read-only | Description |",
        "|---|---|---|---|---|",
    ]
    for t in cat["tools"]:
        desc = (t["description"] or "").replace("|", "\\|").replace("\n", " ")
        ro = "yes" if t["annotations"].get("readOnlyHint") else "no"
        lines.append(f"| `{t['name']}` | {t['title'] or ''} | `{t['scope']}` | {ro} | {desc} |")
    for t in cat["tools"]:
        lines += [
            "",
            f"## `{t['name']}`",
            "",
            "Input schema:",
            "",
            "```json",
            json.dumps(t["input_schema"], indent=2, sort_keys=True),
            "```",
        ]
        if t["output_schema"]:
            lines += [
                "",
                "Output schema:",
                "",
                "```json",
                json.dumps(t["output_schema"], indent=2, sort_keys=True),
                "```",
            ]
    return "\n".join(lines) + "\n"
